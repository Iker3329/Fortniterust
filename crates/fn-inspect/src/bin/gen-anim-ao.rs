//! `gen-anim-ao [fn-inspect.exe] [out.rs]`: generates `crates/fn-animgraph/src/anim_ao.rs`, the CoreAnims_Male AimOffsetBlendSpaces
//! (everything except M_Melee_TwoHanded_AO, which anim_data.rs already has), from `fn-inspect props` of the 1.8 paks
//! (BlendParameters, SampleData, GridSamples). Read-only on the install.
use serde_json::Value;
use std::process::Command;

const DIR: &str = "/Game/Animation/Game/MainPlayer/Poses/Medium/Male/AO/";
const NAMES: [&str; 5] = ["AO_AR_NT_CMM", "AO_Pistol_NT_CMM", "M_GoingCommando_AO", "M_Launcher_AO", "M_NoWep_Relaxed_AO"];

/// A float literal with 9 significant digits (round-trips an f32), always carrying a `.` or an exponent.
fn lit(v: f64) -> String {
    if v == 0.0 { return "0.0".into(); }
    let s = format!("{:.8e}", v);
    let (m, e) = s.split_once('e').unwrap();
    let e: i32 = e.parse().unwrap();
    let neg = v < 0.0;
    let digits: String = m.chars().filter(|c| c.is_ascii_digit()).collect();
    let out = if !(-5..9).contains(&e) {
        let m = m.trim_end_matches('0').trim_end_matches('.');
        format!("{m}E{}{:02}", if e < 0 { "-" } else { "+" }, e.abs())
    } else {
        let s = if e >= 0 { let k = e as usize + 1; format!("{}.{}", &digits[..k], &digits[k..]) } else { format!("0.{}{}", "0".repeat((-e - 1) as usize), digits) };
        let s = s.trim_end_matches('0').trim_end_matches('.').to_string();
        if neg { format!("-{s}") } else { s }
    };
    if out.contains('.') || out.contains('E') { out } else { format!("{out}.0") }
}

fn num(v: &Value, default: f64) -> f64 { v.as_f64().unwrap_or(default) }

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let inspect = args.first().cloned().unwrap_or_else(|| concat!(env!("CARGO_MANIFEST_DIR"), "/../../target/release/fn-inspect.exe").into());
    let out_path = args.get(1).cloned().unwrap_or_else(|| concat!(env!("CARGO_MANIFEST_DIR"), "/../fn-animgraph/src/anim_ao.rs").into());
    let mut out = String::from("// GENERATED by `cargo run -p fn-inspect --bin gen-anim-ao` from the original paks (fn-inspect props) -- do not edit by hand.\n// Same shape as anim_data.rs (BsDef / BsSample / GridElem come from graph.rs, which include!s this file).\n");
    let mut ids = vec![];
    for n in NAMES {
        let o = Command::new(&inspect).args(["props", &format!("{DIR}{n}")]).output().unwrap_or_else(|e| panic!("run {inspect}: {e}"));
        assert!(o.status.success(), "fn-inspect props {n} failed: {}", String::from_utf8_lossy(&o.stderr));
        let json: Value = serde_json::from_slice(&o.stdout).expect("fn-inspect JSON");
        let x = json["exports"].as_array().unwrap().iter().find(|e| e["name"] == n).unwrap_or_else(|| panic!("{n}: export missing"));
        let p = &x["properties"];
        let cls = x["class"].as_str().unwrap();
        let bps = [&p["BlendParameters"], &p["BlendParameters[1]"]];
        let grid = |bp: &Value| bp["GridNum"].as_i64().unwrap_or(4);
        let ax: Vec<String> = bps.iter().map(|bp| format!("Axis{{min:{},max:{},grid:{},interp_time:0.0,interp_type:\"BSIT_Average\"}}", lit(num(&bp["Min"], 0.)), lit(num(&bp["Max"], 0.)), grid(bp))).collect();
        let samples: Vec<String> = p["SampleData"].as_array().unwrap().iter().map(|s| {
            let anim = s["Animation"].as_str().unwrap().rsplit('/').next().unwrap().split('.').next().unwrap();
            let sv = s["SampleValue"].as_array().unwrap();
            format!("BsSample{{anim:\"{anim}\",pos:[{},{}],rate:{}}}", lit(num(&sv[0], 0.)), lit(num(&sv[1], 0.)), lit(num(&s["RateScale"], 1.)))
        }).collect();
        let field = |g: &Value, k: &str, i: usize, d: f64| num(&g[if i == 0 { k.to_string() } else { format!("{k}[{i}]") }], d);
        let gridv: Vec<String> = p["GridSamples"].as_array().unwrap().iter().map(|g| {
            let idx: Vec<String> = (0..3).map(|i| (field(g, "Indices", i, -1.) as i64).to_string()).collect();
            let w: Vec<String> = (0..3).map(|i| lit(field(g, "Weights", i, 0.))).collect();
            format!("GridElem{{idx:[{}],w:[{}]}}", idx.join(","), w.join(","))
        }).collect();
        let expect = (grid(bps[0]) + 1) * (grid(bps[1]) + 1);
        assert_eq!(gridv.len() as i64, expect, "{n}: grid element count");
        let id = n.to_uppercase();
        ids.push(format!("&{id}"));
        out += &format!("pub static {id}_SAMPLES:&[BsSample]=&[{}];\n", samples.join(","));
        out += &format!("pub static {id}_GRID:&[GridElem]=&[{}];\n", gridv.join(","));
        out += &format!("pub static {id}:BsDef=BsDef{{name:\"{n}\",class:\"{cls}\",axes:[{}],target_weight_speed:0.0,axis_to_scale:\"BSA_None\",sample_index_with_markers:-1,mesh_space_rotation:false,samples:{id}_SAMPLES,grid:{id}_GRID}};\n", ax.join(","));
    }
    out += &format!("pub static ALL_AIM_OFFSETS:&[&BsDef]=&[{}];\n", ids.join(","));
    std::fs::write(&out_path, &out).unwrap_or_else(|e| panic!("write {out_path}: {e}"));
    println!("wrote {out_path}: {} aim offsets, {} bytes", NAMES.len(), out.len());
}
