//! UI material code generator (port of tools/ui-material-gen.cjs): for every listed material emit
//! `<name>_cb(p) -> [[f32; 4]; N]`, the material constant buffer built from the cooked uniform expression set (`p(name, cooked_default)`
//! looks every parameter up), and `<name>_ps`, the compiled Slate pixel shader translated to Rust.

use crate::extract::scan_blobs;
use crate::spec::package_bytes;
use crate::uniform::{package_names, parse_set, Expr, UniformSet};
use fn_dxbc::codegen::{rust_prelude, translate_rust};
use fn_dxbc::Shader;
use fn_pak::PakSet;
use std::fmt::Write;

pub struct UiEntry { pub name: String, pub package: String, pub shader_id: usize }

fn f(x: f32) -> String {
    if x.is_nan() || x.is_infinite() { return format!("f32::from_bits({:#010x})", x.to_bits()); }
    let s = format!("{x:?}");
    format!("{s}_f32")
}
fn v4(v: [f32; 4]) -> String { format!("[{}]", v.iter().map(|x| f(*x)).collect::<Vec<_>>().join(", ")) }

fn expr_rs(e: &Expr) -> Result<String, String> {
    Ok(match e {
        Expr::VectorParameter { name, default } => format!("p({name:?}, {})", v4(*default)),
        Expr::ScalarParameter { name, default } => format!("p({name:?}, {})", v4([*default; 4])),
        Expr::Constant { value, .. } => v4(*value),
        Expr::ComponentSwizzle { e, idx, .. } => format!("vswz({}, [{}, {}, {}, {}])", expr_rs(e)?, idx[0], idx[1], idx[2], idx[3]),
        Expr::AppendVector { a, b, num_a } => format!("vapp({}, {}, {num_a})", expr_rs(a)?, expr_rs(b)?),
        Expr::FoldedMath { a, b, op, .. } => {
            let f = match op { 0 => "vadd", 1 => "vsub", 2 => "vmul", 3 => "vdiv", 4 => "vdot", o => return Err(format!("FoldedMath op {o}")) };
            format!("{f}({}, {})", expr_rs(a)?, expr_rs(b)?)
        }
        Expr::TrigMath { x, op, .. } => format!("{}({})", match op { 0 => "vsin", 1 => "vcos", o => return Err(format!("TrigMath op {o}")) }, expr_rs(x)?),
        other => return Err(format!("expression {other:?} has no constant-buffer value")),
    })
}

pub const HELPERS: &str = r#"fn vadd(a: [f32; 4], b: [f32; 4]) -> [f32; 4] { [a[0] + b[0], a[1] + b[1], a[2] + b[2], a[3] + b[3]] }
fn vsub(a: [f32; 4], b: [f32; 4]) -> [f32; 4] { [a[0] - b[0], a[1] - b[1], a[2] - b[2], a[3] - b[3]] }
fn vmul(a: [f32; 4], b: [f32; 4]) -> [f32; 4] { [a[0] * b[0], a[1] * b[1], a[2] * b[2], a[3] * b[3]] }
fn vdiv(a: [f32; 4], b: [f32; 4]) -> [f32; 4] { let d = |x: f32, y: f32| if y == 0.0 { 0.0 } else { x / y }; [d(a[0], b[0]), d(a[1], b[1]), d(a[2], b[2]), d(a[3], b[3])] }
fn vdot(a: [f32; 4], b: [f32; 4]) -> [f32; 4] { let s = a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3]; [s; 4] }
fn vsin(a: [f32; 4]) -> [f32; 4] { [a[0].sin(), a[1].sin(), a[2].sin(), a[3].sin()] }
fn vcos(a: [f32; 4]) -> [f32; 4] { [a[0].cos(), a[1].cos(), a[2].cos(), a[3].cos()] }
fn vswz(a: [f32; 4], i: [i8; 4]) -> [f32; 4] { let g = |k: i8| if k >= 0 { a[k as usize] } else { 0.0 }; [g(i[0]), g(i[1]), g(i[2]), g(i[3])] }
fn vapp(a: [f32; 4], b: [f32; 4], n: usize) -> [f32; 4] { let mut o = [0.0_f32; 4]; for k in 0..4 { o[k] = if k < n { a[k] } else { b[k - n] }; } o }
"#;

/// `<name>_cb` for an evaluated set.
pub fn cb_function(name: &str, set: &UniformSet) -> Result<String, String> {
    let nv = set.vectors.len();
    let regs = nv + set.scalars.len().div_ceil(4);
    let mut s = String::new();
    let _ = writeln!(s, "pub fn {name}_cb(p: &dyn Fn(&str, [f32; 4]) -> [f32; 4]) -> [[f32; 4]; {regs}] {{");
    let _ = writeln!(s, "    let mut cb = [[0.0_f32; 4]; {regs}];");
    for (i, e) in set.vectors.iter().enumerate() { let _ = writeln!(s, "    cb[{i}] = {};", expr_rs(e)?); }
    for (i, e) in set.scalars.iter().enumerate() { let _ = writeln!(s, "    cb[{}][{}] = {}[0];", nv + (i >> 2), i & 3, expr_rs(e)?); }
    let _ = writeln!(s, "    cb\n}}");
    Ok(s)
}

pub fn generate(set: &PakSet, entries: &[UiEntry]) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("//! GENERATED by `fn-dxbc gen-ui` from the 1.8 cooked materials (replaces tools/ui-material-gen.cjs). Do not edit by hand.\n//! Each `<name>_ps` is the compiled Slate pixel shader translated instruction for instruction, each `<name>_cb` builds the material\n//! constant buffer by evaluating the cooked uniform expression set, looking every parameter up by name (`p(name, cooked_default)`).\n");
    out.push_str("#![allow(dead_code, clippy::all, unused_mut, unused_variables, unused_assignments, unused_parens)]\n\n");
    out.push_str(rust_prelude());
    out.push('\n');
    out.push_str(HELPERS);
    for e in entries {
        let uexp = package_bytes(set, &e.package)?;
        let uasset = set.read_game(&e.package, "uasset").map_err(|x| x.to_string())?.into_owned();
        let names = package_names(&uasset, &uexp)?;
        let us = parse_set(&uexp, &names)?;
        let blob = scan_blobs(&uexp).into_iter().find(|b| b.id == e.shader_id).ok_or_else(|| format!("{}: no shader stream at {}", e.package, e.shader_id))?;
        let sh = Shader::parse(&blob.bytes).map_err(|x| x.to_string())?;
        let _ = writeln!(out, "\n// ==== {} ({} shader_{}) ====", e.name, e.package, e.shader_id);
        out.push_str(&cb_function(&e.name, &us)?);
        out.push_str(&translate_rust(&sh, &format!("{}_ps", e.name)).map_err(|x| x.0)?);
    }
    Ok(out)
}
