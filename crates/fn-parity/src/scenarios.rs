#[cfg(test)]
mod tests {
    use super::*;
    #[test] fn dir_script_has_24_cases_and_3_turn_shots() { let g = dir_script(); assert_eq!(g.pairs.len(), 27); assert!(g.script.contains("89 shot dir-jog-F")); assert!(g.script.contains("2424 shot dir-turn-25")); assert!(g.script.contains("end 2520")); }
    #[test] fn light_script_skips_shadow_off_and_resizes() { let g = light_script(); assert!(g.pairs.iter().all(|p| !p.old.contains("-off-")) && g.pairs.iter().any(|p| p.old == "light-high-3840x2160")); assert!(g.script.contains("resize 2560x1080")); }
    #[test] fn sky_script_names_follow_the_old_files() { let g = sky_script(); assert!(g.pairs.iter().any(|p| p.old == "sky-pitch+00" && p.new == "sky-pitch+00-1280x720.png")); assert!(g.pairs.iter().any(|p| p.old == "sky-size-4x3-1024x768-up" && p.new == "sky-size-4x3-up-1024x768.png")); let (y, e) = sun_yaw_pitch(); assert!((y - 90.).abs() < 0.1 && (e - 61.2).abs() < 0.5); }
}
